  {"claim": "RAG技术由Lewis等人于2023年首次提出", "verdict": "矛盾", "evidence": "Lewis et al. (2020) proposed Retrieval-Augmented Generation"},
  {"claim": "RAG主要用于医疗领域", "verdict": "证据不足", "evidence": ""}
